def _softmax(x: np.ndarray, tau: float = 1.0) -> np.ndarray:
    z = x / tau
    z = z - z.max(axis=-1, keepdims=True)
    e = np.exp(z)
    return e / e.sum(axis=-1, keepdims=True)


def make_gridworld(size: int = 5, gamma: float = 0.95) -> TabularMDP:
    """Classic 4-connected grid. Goal at bottom-right (reward +1, terminal)."""
    S = size * size
    A = 4  # up, right, down, left
    P = np.zeros((S, A, S))
    R = np.zeros((S, A))
    goal = S - 1
    terminals = np.zeros(S, dtype=bool)
    terminals[goal] = True
    R[:, :] = -0.01  # small step cost

    def coord(i: int) -> tuple[int, int]:
        return divmod(i, size)

    def idx(r: int, c: int) -> int:
        return r * size + c

    for s in range(S):
        if s == goal:
            continue
        r, c = coord(s)
        moves = {
            0: (max(r - 1, 0), c),  # up
            1: (r, min(c + 1, size - 1)),  # right
            2: (min(r + 1, size - 1), c),  # down
            3: (r, max(c - 1, 0)),  # left
        }
        for a, (rr, cc) in moves.items():
            ns = idx(rr, cc)
            P[s, a, ns] = 1.0
            # reward is awarded on the step that *enters* the goal
            if ns == goal:
                R[s, a] = 1.0
    mu = np.zeros(S)
    mu[0] = 1.0
    return TabularMDP("GridWorld", P, R, mu, gamma, terminals)


def make_river_crossing(width: int = 5, gamma: float = 0.95) -> TabularMDP:
    """Grid with a river band; only the bridge cell is safe to cross."""
    size = width
    S = size * size
    A = 4
    P = np.zeros((S, A, S))
    R = np.zeros((S, A))
    goal = S - 1
    terminals = np.zeros(S, dtype=bool)
    terminals[goal] = True
    R[:, :] = -0.02

    def coord(i: int) -> tuple[int, int]:
        return divmod(i, size)

    def idx(r: int, c: int) -> int:
        return r * size + c

    # river occupies row (size // 2); only column 0 is a bridge (safe)
    river_row = size // 2
    bridge_col = 0

    def is_river(r: int, c: int) -> bool:
        return r == river_row and c != bridge_col

    for s in range(S):
        if s == goal:
            continue
        r, c = coord(s)
        moves = {
            0: (max(r - 1, 0), c),
            1: (r, min(c + 1, size - 1)),
            2: (min(r + 1, size - 1), c),
            3: (r, max(c - 1, 0)),
        }
        for a, (rr, cc) in moves.items():
            if is_river(rr, cc):
                # falling in the river sends you back to start (state 0)
                P[s, a, 0] = 1.0
                R[s, a] = -1.0
            else:
                ns = idx(rr, cc)
                P[s, a, ns] = 1.0
                # reward is awarded on the step that *enters* the goal
                if ns == goal:
                    R[s, a] = 1.0
    mu = np.zeros(S)
    mu[0] = 1.0
    return TabularMDP("RiverCrossing", P, R, mu, gamma, terminals)


def make_chain_mdp(n: int = 10, gamma: float = 0.95) -> TabularMDP:
    """Chain of n states; two actions (left/right). Reward at the right end."""
    S = n
    A = 2  # 0=move left, 1=move right
    P = np.zeros((S, A, S))
    R = np.zeros((S, A))
    terminals = np.zeros(S, dtype=bool)
    terminals[n - 1] = True
    R[:, :] = -0.05
    R[n - 1, :] = 1.0
    for s in range(S):
        # left action: stay or go left (mostly left)
        P[s, 0, max(s - 1, 0)] = 0.9
        P[s, 0, min(s + 1, S - 1)] = 0.1
        # right action: mostly go right, but with some slip
        P[s, 1, min(s + 1, S - 1)] = 0.9
        P[s, 1, max(s - 1, 0)] = 0.1
    mu = np.zeros(S)
    mu[0] = 1.0
    return TabularMDP("ChainMDP", P, R, mu, gamma, terminals)


def make_tiny_random(n: int = 8, a: int = 2, gamma: float = 0.9, seed: int = 7) -> TabularMDP:
    """Small random MDP — a stress test for OPE variance/coverage."""
    rng = np.random.default_rng(seed)
    P = rng.dirichlet(np.ones(n), size=(n, a))
    R = rng.normal(0.0, 1.0, size=(n, a))
    mu = rng.dirichlet(np.ones(n))
    terminals = np.zeros(n, dtype=bool)
    terminals[n - 1] = True
    return TabularMDP("TinyRandom", P, R, mu, gamma, terminals)


def make_behaviour_policy(mdp: TabularMDP, tau: float = 0.6, seed: int = 0) -> np.ndarray:
    """A suboptimal-but-reasonable stochastic behaviour policy with full support.

    Full support (every action positive) is what keeps importance weights
    finite — essential for WIS to be well defined.
    """
    rng = np.random.default_rng(seed)
    rough = rng.normal(size=(mdp.n_states, mdp.n_actions))
    # bias towards the goal direction a little so it is not pure noise
    return _softmax(rough, tau=tau)


# convenience: a simple policy container used by the pipeline
class MatrixPolicy:
    """Wraps an (n_states, n_actions) matrix as a Policy."""

    def __init__(self, matrix: np.ndarray) -> None:
        self.matrix = np.asarray(matrix, dtype=float)
        self.n_states, self.n_actions = self.matrix.shape

    def probs(self, states: np.ndarray) -> np.ndarray:
        return self.matrix[np.asarray(states, dtype=np.int64)]

    def act(self, state: int, rng: np.random.Generator | None = None) -> int:
        rng = rng or np.random.default_rng()
        return int(rng.choice(self.n_actions, p=self.matrix[state]))

    def greedy(self) -> MatrixPolicy:
        pi = np.zeros_like(self.matrix)
        pi[np.arange(self.n_states), self.matrix.argmax(axis=1)] = 1.0
        return MatrixPolicy(pi)
