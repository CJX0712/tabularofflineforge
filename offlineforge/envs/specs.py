"""Tabular MDP definitions + offline dataset generation.

Four small-but-non-trivial environments are provided: a GridWorld, a River
Crossing puzzle, a Chain MDP, and a Tiny Random MDP. Every one is *exact* —
the full model (P, R, mu, gamma) is known — which is precisely what lets
``solver.py`` compute ground-truth policy values to arbitrary precision.

The offline dataset, however, is generated by a *behaviour policy* and is the
only thing OPE estimators are allowed to see.
"""

from __future__ import annotations

import numpy as np

from ..core.types import MDPSpec, TransitionDataset
from .solver import policy_value


class TabularMDP:
    """A known tabular MDP with logging + exact-evaluation support."""

    def __init__(
        self,
        name: str,
        P: np.ndarray,  # (S, A, S)
        R: np.ndarray,  # (S, A)
        mu: np.ndarray,  # (S,)
        gamma: float,
        terminals: np.ndarray | None = None,
    ) -> None:
        self.name = name
        self.P = np.asarray(P, dtype=float)
        self.R = np.asarray(R, dtype=float)
        self.mu = np.asarray(mu, dtype=float)
        if abs(self.mu.sum() - 1.0) > 1e-6:
            self.mu = self.mu / self.mu.sum()
        self.gamma = float(gamma)
        self.n_states, self.n_actions, _ = self.P.shape
        self.spec = MDPSpec(name, self.n_states, self.n_actions, self.gamma)
        self.terminals = (
            np.zeros(self.n_states, dtype=bool)
            if terminals is None
            else np.asarray(terminals, dtype=bool)
        )
        # force no transition out of terminal states
        for s in np.where(self.terminals)[0]:
            self.P[s] = 0.0
            self.P[s, :, s] = 1.0
            self.R[s] = 0.0

    # ----- exact evaluation -----
    def exact_value(self, policy_matrix: np.ndarray) -> float:
        return policy_value(policy_matrix, self.P, self.R, self.mu, self.gamma)

    def optimal_value(self) -> float:
        from .solver import optimal_policy

        return self.exact_value(optimal_policy(self.P, self.R, self.gamma))

    # ----- sampling -----
    def step(self, s: int, a: int, rng: np.random.Generator) -> tuple[int, float, bool]:
        s_next = int(rng.choice(self.n_states, p=self.P[s, a]))
        return s_next, float(self.R[s, a]), bool(self.terminals[s_next])

    def generate_dataset(
        self,
        policy_matrix: np.ndarray,
        n_episodes: int,
        max_steps: int,
        rng: np.random.Generator,
    ) -> TransitionDataset:
        S, A, Rr = [], [], []
        Ns, D, Bp, Eid, Init = [], [], [], [], []
        for ep in range(n_episodes):
            s = int(rng.choice(self.n_states, p=self.mu))
            done = False
            for t in range(max_steps):
                a = int(rng.choice(self.n_actions, p=policy_matrix[s]))
                s_next, r, done = self.step(s, a, rng)
                S.append(s)
                A.append(a)
                Rr.append(r)
                Ns.append(s_next)
                D.append(done)
                Bp.append(float(policy_matrix[s, a]))
                Eid.append(ep)
                Init.append(t == 0)
                s = s_next
                if done:
                    break
        return TransitionDataset(
            states=np.asarray(S, dtype=np.int64),
            actions=np.asarray(A, dtype=np.int64),
            rewards=np.asarray(Rr, dtype=np.float32),
            next_states=np.asarray(Ns, dtype=np.int64),
            dones=np.asarray(D, dtype=bool),
            behavior_probs=np.asarray(Bp, dtype=np.float32),
            episode_ids=np.asarray(Eid, dtype=np.int64),
            is_initial=np.asarray(Init, dtype=bool),
            spec=self.spec,
        )


